console.log("OPERADORES EN TONY BIBLIOTECA");

numero1 = 20;
numero2 = 5;

console.log("Suma:");
suma = numero1 + numero2;
console.log("Resultado:", suma);

console.log("Resta:");
resta = numero1 - numero2;
console.log("Resultado:", resta);

console.log("Multiplicación:");
multiplicacion = numero1 * numero2;
console.log("Resultado:", multiplicacion);

console.log("División:");
division = numero1 / numero2;
console.log("Resultado:", division);

console.log("Módulo:");
modulo = numero1 % numero2;
console.log("Resultado:", modulo);

console.log("Potencia:");
exponenciacion = numero1 ** numero2;
console.log("Resultado:", exponenciacion);

console.log("OPERADORES DE COMPARACIÓN:");
console.log("Igualdad débil ==", "5" == 5);
console.log("Igualdad estricta ===", "5" === 5);
console.log("Desigualdad débil !=", "5" != 5);
console.log("Desigualdad estricta !==", "5" !== 5);
console.log("Mayor que >", 5 > 3);
console.log("Menor que <", 5 < 3);
console.log("Mayor o igual que >=", 5 >= 5);
console.log("Menor o igual que <=", 5 <= 3);

console.log("OPERADORES LÓGICOS:");
console.log("Y AND &&", true && false);
console.log("O OR ||", true || false);
console.log("Negación NOT !", !(true === false));
